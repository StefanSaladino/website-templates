 assert.equal(auto.total,4);
 assert.equal(auto.downloaded,0);
 assert.equal(auto.errors,0);
 assert(auto.assets.every(item=>item.reviewStatus==='needs-review'&&item.candidateStatus==='offline-no-image-inspection'));
